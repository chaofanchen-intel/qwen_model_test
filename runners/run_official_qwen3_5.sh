#!/bin/bash
#
# Official llm_bench runner for Qwen3.5 visual_text_gen.
#
# Usage:
#   ./tests/runners/run_official_qwen3_5.sh
#   ./tests/runners/run_official_qwen3_5.sh GPU
#   MODELS="0.8B 2B" QUANTS="INT4" ./tests/runners/run_official_qwen3_5.sh GPU
#   MODEL=/abs/path/to/Qwen3.5-0.8B-INT4 ITERS=10 INFER_COUNT=512 ./tests/runners/run_official_qwen3_5.sh GPU
#
# Env overrides (defaults in []):
#   DEVICE                    [CPU GPU NPU]       positional args override
#   MODEL                     []                  explicit model path(s), overrides auto discovery and MODELS/QUANTS
#   MODELS                    []                  optional size keys; empty => auto-discover models/Qwen3.5-*
#   QUANTS                    [INT4]              used only with MODELS
#   TASK                      [visual_text_gen]
#   ITERS                     [10]                measured iterations; official warm-up iter 0 is extra
#   INFER_COUNT               [512]               passed as -ic/max_new_tokens
#   BATCH_SIZE                [1]
#   PROMPT_FILE               [tests/prompts/qwen3.5_1k.jsonl]  ~1000-tok prompt (matches our --input-tokens 1000 default)
#   PROMPT_INDEX              [0]                 first long prompt approximates 1k input; empty means all prompts
#   IMAGES                    []                  optional path passed to -i/--images
#   NUM_BEAMS                 [1]
#   APPLY_CHAT_TEMPLATE       [0]
#   DISABLE_PROMPT_PERMUTATION[0]
#   LOAD_CONFIG               []                  optional JSON file/string passed as -lc (overrides GPU/NPU defaults)
#   DEFAULT_LOAD_CONFIG       [{"PERFORMANCE_HINT":"LATENCY","ATTENTION_BACKEND":"PA"}]  default -lc on ALL non-NPU devices; set empty to disable
#   NPU_LOAD_CONFIG           [auto]              JSON string/file for NPU VLM static config; set empty to disable
#   NPU_MAX_PROMPT_LEN        [1024]
#   NPU_MIN_RESPONSE_LEN      [512]
#   NPU_PREFILL_CHUNK_SIZE    [2048]
#   NPU_CACHE_DIR             [$PROJECT_DIR/cache_npu/qwen3_5]
#   RESOURCE_MONITOR          [1]
#   RESOURCE_INTERVAL_MS      [500]
#   RESOURCE_GPU_COMMAND      []                  overrides auto sudo -n xpu-smi command
#   SUDO_REFRESH              [1]                 run sudo -v before resource monitoring
#   MEMORY_CONSUMPTION        [0]                 official -mc
#   MEMORY_INTERVAL           [0.05]
#   INTERVAL                  [0]                 optional cooldown seconds between runs
#   LOG_DIR / REPORT_DIR      [tests/logs/official_qwen3_5_<model>_<device>_<ts>]
#   BENCHMARK_DIR             [results]
#   BENCHMARK_CSV             [$BENCHMARK_DIR/benchmark_qwen3_5_official.csv]
#   BENCHMARK_JSON            [$BENCHMARK_DIR/benchmark_qwen3_5_official.json]
#   EXTRA_BENCH_ARGS          []                  appended to benchmark.py

set -euo pipefail

if [ "${1:-}" = "--help" ] || [ "${1:-}" = "-h" ]; then
    sed -n '2,40p' "$0"
    exit 0
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TESTS_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
PROJECT_DIR="$(cd "$TESTS_DIR/.." && pwd)"
LLM_BENCH_DIR="$PROJECT_DIR/openvino.genai/tools/llm_bench"

source "$SCRIPT_DIR/_common.sh"
if [ -z "${PYTHON:-}" ] && [ -x "/home/user/envs/qwen_env/bin/python" ]; then
    PYTHON="/home/user/envs/qwen_env/bin/python"
fi
bench_select_python

DEVICE="${DEVICE:-CPU GPU NPU}"
bench_parse_devices "$@"

TASK="${TASK:-visual_text_gen}"
ITERS="${ITERS:-10}"
INFER_COUNT="${INFER_COUNT:-512}"
BATCH_SIZE="${BATCH_SIZE:-1}"
# Default prompt: the ~1000-token JSONL generated by build_prompt_jsonl.py with the
# Qwen3.5 OV tokenizer, so the official path uses the same ~1000-tok input as our own
# python/C++ benchmarks (which default to --input-tokens 1000). Override via PROMPT_FILE.
PROMPT_FILE="${PROMPT_FILE:-$TESTS_DIR/prompts/qwen3.5_1k.jsonl}"
PROMPT_INDEX="${PROMPT_INDEX:-0}"
IMAGES="${IMAGES:-}"
NUM_BEAMS="${NUM_BEAMS:-1}"
RESOURCE_MONITOR="${RESOURCE_MONITOR:-1}"
RESOURCE_INTERVAL_MS="${RESOURCE_INTERVAL_MS:-1000}"
RESOURCE_GPU_COMMAND="${RESOURCE_GPU_COMMAND:-}"
SUDO_REFRESH="${SUDO_REFRESH:-1}"
MEMORY_CONSUMPTION="${MEMORY_CONSUMPTION:-0}"
MEMORY_INTERVAL="${MEMORY_INTERVAL:-0.05}"
LOAD_CONFIG="${LOAD_CONFIG:-}"
NPU_MAX_PROMPT_LEN="${NPU_MAX_PROMPT_LEN:-1000}"
NPU_MIN_RESPONSE_LEN="${NPU_MIN_RESPONSE_LEN:-512}"
NPU_PREFILL_CHUNK_SIZE="${NPU_PREFILL_CHUNK_SIZE:-2048}"
NPU_CACHE_DIR="${NPU_CACHE_DIR:-$PROJECT_DIR/cache_npu/qwen3_5}"
if [ -z "${NPU_LOAD_CONFIG+x}" ]; then
    NPU_LOAD_CONFIG="{\"MAX_PROMPT_LEN\":$NPU_MAX_PROMPT_LEN,\"MIN_RESPONSE_LEN\":$NPU_MIN_RESPONSE_LEN,\"CACHE_DIR\":\"$NPU_CACHE_DIR\",\"NPUW_LLM_PREFILL_CHUNK_SIZE\":$NPU_PREFILL_CHUNK_SIZE}"
fi
APPLY_CHAT_TEMPLATE="${APPLY_CHAT_TEMPLATE:-0}"
DISABLE_PROMPT_PERMUTATION="${DISABLE_PROMPT_PERMUTATION:-0}"
INTERVAL="${INTERVAL:-0}"
EXTRA_BENCH_ARGS="${EXTRA_BENCH_ARGS:-}"
# Device-agnostic default -lc: LATENCY perf hint + PA attention backend (passed to the
# official benchmark.py as inline JSON via -lc). -lc is NOT device-specific; this default
# is applied on every device EXCEPT NPU (NPU needs its own static NPUW config and does not
# support PA, so it uses NPU_LOAD_CONFIG instead). Set DEFAULT_LOAD_CONFIG= (empty) to
# disable, or LOAD_CONFIG=... to override on all devices.
DEFAULT_LOAD_CONFIG="${DEFAULT_LOAD_CONFIG-{\"PERFORMANCE_HINT\":\"LATENCY\",\"ATTENTION_BACKEND\":\"PA\"}}"

bench_validate_load_config "$LOAD_CONFIG" "LOAD_CONFIG"
[ -n "$LOAD_CONFIG" ] && LOAD_CONFIG="$(bench_resolve_load_config "$LOAD_CONFIG")"
bench_validate_load_config "${NPU_LOAD_CONFIG:-}" "NPU_LOAD_CONFIG"
[ -n "${NPU_LOAD_CONFIG:-}" ] && NPU_LOAD_CONFIG="$(bench_resolve_load_config "$NPU_LOAD_CONFIG")"
bench_validate_load_config "${DEFAULT_LOAD_CONFIG:-}" "DEFAULT_LOAD_CONFIG"
[ -n "${DEFAULT_LOAD_CONFIG:-}" ] && DEFAULT_LOAD_CONFIG="$(bench_resolve_load_config "$DEFAULT_LOAD_CONFIG")"
PROMPT_FILE="$(bench_resolve_file "$PROMPT_FILE" "PROMPT_FILE")"
if [ -n "$IMAGES" ] && [ ! -e "$IMAGES" ]; then
    echo "[ERROR] IMAGES path not found: $IMAGES" >&2
    exit 1
fi

MODEL_PATHS=()
MODEL_LABELS=()
MODEL_PATHS_RESOLVED=()
if [ -n "${MODEL:-}" ]; then
    read -ra MODEL_PATHS <<< "$MODEL"
    for model_path in "${MODEL_PATHS[@]}"; do
        resolved_model_path="$(bench_resolve_model_dir "$model_path" "MODEL")"
        MODEL_PATHS_RESOLVED+=("$resolved_model_path")
        MODEL_LABELS+=("$(bench_sanitize_label "$(basename "$resolved_model_path")")")
    done
    MODEL_PATHS=("${MODEL_PATHS_RESOLVED[@]}")
elif [ -n "${MODELS:-}" ] || [ -n "${QUANTS:-}" ]; then
    if [ -z "${MODELS:-}" ]; then
        MODEL_SIZES=("0.8B" "2B" "4B")
    else
        read -ra MODEL_SIZES <<< "$MODELS"
    fi
    if [ -z "${QUANTS:-}" ]; then
        QUANT_LIST=("INT4")
    else
        read -ra QUANT_LIST <<< "$QUANTS"
    fi
    for size in "${MODEL_SIZES[@]}"; do
        for quant in "${QUANT_LIST[@]}"; do
            size_norm="$(bench_normalize_size_b "$size")"
            quant_uc=$(echo "$quant" | tr '[:lower:]' '[:upper:]')
            model_path="$PROJECT_DIR/models/Qwen3.5-${size_norm}-${quant_uc}"
            MODEL_PATHS+=("$model_path")
            MODEL_LABELS+=("$(bench_sanitize_label "Qwen3.5-${size_norm}-${quant_uc}")")
        done
    done
else
    mapfile -t MODEL_PATHS < <(bench_discover_model_dirs "Qwen3.5-*" "qwen3.5-*")
    for model_path in "${MODEL_PATHS[@]}"; do
        MODEL_LABELS+=("$(bench_sanitize_label "$(basename "$model_path")")")
    done
fi
if [ "${#MODEL_PATHS[@]}" -eq 0 ]; then
    echo "[ERROR] no Qwen3.5 VLM models found; set MODEL=/path/to/model" >&2
    exit 1
fi

if [ "${#MODEL_LABELS[@]}" -eq 1 ]; then
    MODEL_SET_LABEL="${MODEL_LABELS[0]}"
else
    MODEL_SET_LABEL="multi"
fi
DEVICE_SET_LABEL="$(bench_sanitize_label "${DEVICES[*]}")"
if [ -n "${REPORT_DIR:-}" ] && [ -z "${LOG_DIR:-}" ]; then
    LOG_DIR="$REPORT_DIR"
fi
bench_make_log_dir "official_qwen3_5_${MODEL_SET_LABEL}_${DEVICE_SET_LABEL}"
REPORT_DIR="$LOG_DIR"
BENCHMARK_DIR="${BENCHMARK_DIR:-$PROJECT_DIR/results}"
mkdir -p "$BENCHMARK_DIR"
BENCHMARK_CSV="${BENCHMARK_CSV:-$BENCHMARK_DIR/benchmark_qwen3_5_official.csv}"
BENCHMARK_JSON="${BENCHMARK_JSON:-$BENCHMARK_DIR/benchmark_qwen3_5_official.json}"

PROMPT_ARGS=(-pf "$PROMPT_FILE")
if [ -n "$PROMPT_INDEX" ]; then
    read -ra PROMPT_INDEX_ARR <<< "$PROMPT_INDEX"
    PROMPT_ARGS+=(-pi "${PROMPT_INDEX_ARR[@]}")
fi

EXTRA_ARGS=()
[ "$APPLY_CHAT_TEMPLATE" = "1" ] && EXTRA_ARGS+=(--apply_chat_template)
[ "$DISABLE_PROMPT_PERMUTATION" = "1" ] && EXTRA_ARGS+=(--disable_prompt_permutation)
[ -n "$IMAGES" ] && EXTRA_ARGS+=(-i "$IMAGES")
[ -n "$RESOURCE_GPU_COMMAND" ] && EXTRA_ARGS+=(--resource_gpu_command "$RESOURCE_GPU_COMMAND")
if [ -n "$EXTRA_BENCH_ARGS" ]; then
    read -ra EXTRA_BENCH_ARGS_ARR <<< "$EXTRA_BENCH_ARGS"
    EXTRA_ARGS+=("${EXTRA_BENCH_ARGS_ARR[@]}")
fi

if [ "$RESOURCE_MONITOR" = "1" ] && [ "$SUDO_REFRESH" = "1" ]; then
    bench_refresh_sudo
fi

echo "============================================================"
echo " Official Qwen3.5 visual_text_gen benchmark.py Runner"
echo "============================================================"
echo " Devices:        ${DEVICES[*]}"
echo " Models:         ${MODEL_LABELS[*]}"
echo " Task:           $TASK"
echo " Prompt file:    $PROMPT_FILE"
echo " Prompt idx:     ${PROMPT_INDEX:-<all>}"
[ -n "$IMAGES" ] && echo " Images:         $IMAGES"
echo " infer_count:    $INFER_COUNT"
echo " Iterations:     $ITERS (+1 warm-up)"
echo " batch_size:     $BATCH_SIZE"
echo " num_beams:      $NUM_BEAMS"
echo " chat_tmpl:      $APPLY_CHAT_TEMPLATE"
echo " disable_perm:   $DISABLE_PROMPT_PERMUTATION"
echo " Load config:    ${LOAD_CONFIG:-<none>}"
echo " Default config: ${DEFAULT_LOAD_CONFIG:-<none>} (non-NPU)"
echo " NPU config:     ${NPU_LOAD_CONFIG:-<none>}"
echo " Resource mon:   $RESOURCE_MONITOR (${RESOURCE_INTERVAL_MS}ms)"
echo " Memory mode:    $MEMORY_CONSUMPTION (${MEMORY_INTERVAL}s)"
echo " Log dir:        $LOG_DIR"
echo " Benchmark CSV:  $BENCHMARK_CSV"
echo " Benchmark JSON: $BENCHMARK_JSON"
echo "============================================================"
echo ""

bench_write_manifest "$LOG_DIR/run_info.txt" \
    "runner:           official_qwen3_5" \
    "task:             $TASK" \
    "devices:          ${DEVICES[*]}" \
    "models:           ${MODEL_PATHS[*]}" \
    "prompt_file:      $PROMPT_FILE" \
    "prompt_index:     ${PROMPT_INDEX:-<all>}" \
    "images:           $IMAGES" \
    "infer_count:      $INFER_COUNT" \
    "iters:            $ITERS" \
    "batch_size:       $BATCH_SIZE" \
    "num_beams:        $NUM_BEAMS" \
    "apply_chat_tpl:   $APPLY_CHAT_TEMPLATE" \
    "disable_perm:     $DISABLE_PROMPT_PERMUTATION" \
    "load_config:      $LOAD_CONFIG" \
    "default_load_config: ${DEFAULT_LOAD_CONFIG:-}" \
    "npu_load_config:  ${NPU_LOAD_CONFIG:-}" \
    "resource_monitor: $RESOURCE_MONITOR" \
    "resource_interval:$RESOURCE_INTERVAL_MS" \
    "memory_mode:      $MEMORY_CONSUMPTION" \
    "benchmark_csv:    $BENCHMARK_CSV" \
    "benchmark_json:   $BENCHMARK_JSON"

FIRST_RUN=true
for idx in "${!MODEL_PATHS[@]}"; do
    model_path="${MODEL_PATHS[$idx]}"
    model_label="${MODEL_LABELS[$idx]}"
    if [ ! -d "$model_path" ]; then
        echo "[SKIP] Model not found: $model_path"
        continue
    fi
    for dev in "${DEVICES[@]}"; do
        if [ "$FIRST_RUN" = true ]; then
            FIRST_RUN=false
        elif [ "${INTERVAL:-0}" != "0" ]; then
            echo ""
            echo "[WAIT] cooling ${INTERVAL}s before next test..."
            sleep "$INTERVAL"
        fi
        run_name="$(bench_sanitize_label "${model_label}_${dev}_ic${INFER_COUNT}_n${ITERS}")"
        csv_out="$LOG_DIR/${run_name}_iters.csv"
        json_out="$LOG_DIR/${run_name}_iters.json"
        log_file="$LOG_DIR/${run_name}.log"
        echo "============================================================"
        echo "[RUN] $run_name"
        echo "      model: $model_path"
        echo "      log:   $log_file"
        echo "      csv:   $csv_out"
        echo "      json:  $json_out"
        echo "============================================================"

        DEVICE_EXTRA_ARGS=()
        if [ -n "$LOAD_CONFIG" ]; then
            DEVICE_EXTRA_ARGS+=(-lc "$LOAD_CONFIG")
        elif [ "$dev" = "NPU" ]; then
            [ -n "$NPU_LOAD_CONFIG" ] && DEVICE_EXTRA_ARGS+=(-lc "$NPU_LOAD_CONFIG")
        elif [ -n "$DEFAULT_LOAD_CONFIG" ]; then
            DEVICE_EXTRA_ARGS+=(-lc "$DEFAULT_LOAD_CONFIG")
        fi

        cd "$LLM_BENCH_DIR"
        bench_run_with_log "$log_file" \
            "$BENCH_PYTHON" benchmark.py \
                -m "$model_path" \
                -d "$dev" \
                -n "$ITERS" \
                -ic "$INFER_COUNT" \
                "${PROMPT_ARGS[@]}" \
                --task "$TASK" \
                -bs "$BATCH_SIZE" \
                --num_beams "$NUM_BEAMS" \
                -r "$csv_out" \
                -rj "$json_out" \
                --benchmark_csv "$BENCHMARK_CSV" \
                --benchmark_json "$BENCHMARK_JSON" \
                --resource_monitor "$RESOURCE_MONITOR" \
                --resource_monitor_interval "$RESOURCE_INTERVAL_MS" \
                -mc "$MEMORY_CONSUMPTION" \
                --memory_consumption_interval "$MEMORY_INTERVAL" \
                "${DEVICE_EXTRA_ARGS[@]}" \
                "${EXTRA_ARGS[@]}"
    done
done

echo ""
echo "============================================================"
echo " Official Qwen3.5 benchmark complete"
echo " Benchmark CSV:  $BENCHMARK_CSV"
echo " Benchmark JSON: $BENCHMARK_JSON"
echo " Logs:           $LOG_DIR/"
echo "============================================================"